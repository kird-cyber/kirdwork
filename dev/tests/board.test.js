// The Google Sheets record server (leaderboard/Code.gs) under a fake Sheets: PIN, ranks, new-record rank jump, 명예의 전당.
const B = require('./board_mock')();
let pass = 0, fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); c ? pass++ : fail++; };
const day = new Date(Date.now() + 9 * 3600e3).toISOString().slice(0, 10);
const K = n => n.repeat(64).slice(0, 64);
const sub = (nick, key, time, hp, extra) => B.post(Object.assign({ action: 'submit', day, nick, key, time, hp, clear: true, kills: 3, tank: 'rookie', shots: 20, ver: 't', log: [] }, extra || {}));
let r = sub('민수', K('a'), 300, 500);
ok(r.ok && r.rank === 1 && r.prevRank === null && r.best, 'first record: rank 1, no previous rank');
sub('지영', K('b'), 250, 900); sub('0012', K('c'), 400, 100);
r = sub('민수', K('f'), 100, 900);
ok(!r.ok && r.error === 'pin', 'someone else using 민수 with another PIN is refused');
r = sub('0012', K('c'), 200, 300);
ok(r.ok && r.prevRank === 3 && r.rank === 1 && r.best, `new record jumps 3위 → 1위 (got ${r.prevRank} → ${r.rank})`);
r = sub('민수', K('a'), 320, 900);
ok(r.ok && !r.best && r.rank === 3, 'a slower run keeps the best (민수 stays 3위)');
r = sub('지영', K('b'), 250, 950);
ok(r.ok && r.best && r.rank === 2, 'same time, more health left counts as better');
r = B.post({ action: 'submit', day, nick: '현우', key: K('d'), time: 99, hp: 0, clear: false, kills: 1, tank: 'hammer', shots: 9, log: [] });
ok(r.ok && r.clear === false, 'a failed run is saved but not ranked');
const t = B.get({ day, nick: '0012' });
ok(t.ok && t.today.map(x => x.nick).join() === '0012,지영,민수' && t.players === 3, 'today TOP: ' + t.today.map(x => `${x.rank}.${x.nick} ${x.time}s`).join(' · '));
ok(t.me && t.me.today.rank === 1 && t.me.today.time === 200, 'my best and rank come back with the list');
ok(t.fame[0].nick === '0012' && t.fame[0].points === 10 && t.fame[0].firsts === 1, '명예의 전당: 1위 = 10점 (' + t.fame.map(f => `${f.nick} ${f.points}`).join(', ') + ')');
ok(typeof t.today[0].nick === 'string' && t.today[0].nick === '0012', 'number-looking nickname stays text (0012)');
r = B.post({ action: 'submit', day: '2020-01-01', nick: '민수', key: K('a'), time: 50, hp: 1, clear: true, log: [] });
ok(!r.ok && r.error === 'day', 'records for an old day are refused');
r = B.post({ action: 'submit', day, nick: '아주아주긴닉네임입니다', key: K('a'), time: 50, hp: 1, clear: true });
ok(!r.ok && r.error === 'bad', 'too long nickname refused');
ok(B.raw('POST', {}, 'not json').includes('"bad"'), 'garbage body refused');
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
