#!/usr/bin/env python3
"""「알고 계셨나요?」 문장 풀 → dev/src/tips.js
- pools.json : 풀별 [번호, 문장, 근거]  (문서 「케이요새 알고 계셨나요? 문제은행」의 표와 같은 내용)
- grades.json: 풀별 {번호: [등급 A/B/C, 이유]}
등급 가중치 A=3 · B=2 · C=1. 문장이나 등급을 바꾸면 이 스크립트를 다시 돌린 뒤 dev/build.py 로 빌드."""
import json, pathlib
here = pathlib.Path(__file__).resolve().parent
pools = json.loads((here / 'pools.json').read_text(encoding='utf-8'))
grades = json.loads((here / 'grades.json').read_text(encoding='utf-8'))
W = {'A': 3, 'B': 2, 'C': 1}
out, stat = {}, {}
for k, rows in pools.items():
    g = grades[k]; arr = []
    for n, s, _basis in rows:
        gr = g[str(n)][0]
        arr.append([s, W[gr]])
    out[k] = arr
    stat[k] = {x: sum(1 for n, *_ in rows if g[str(n)][0] == x) for x in 'ABC'}
js = ('// 「알고 계셨나요?」 — generated by dev/tips/build_tips.py from dev/tips/pools.json + grades.json (do not edit by hand)\n'
      '// each tip: [text, weight] with 중요도 A=3 · B=2 · C=1; sources: 국가연구개발혁신법 매뉴얼(2026.7) 등, see the doc\n'
      'const TIP_POOLS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
(here.parent / 'src' / 'tips.js').write_text(js, encoding='utf-8')
print('tips.js', len(js), 'bytes', stat)
